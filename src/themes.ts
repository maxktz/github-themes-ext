// Theme palettes. Each theme names a handful of roles; the generator
// (scripts/generate.ts) maps every GitHub color variable onto these roles.

export interface Syntax {
  comment: string;
  keyword: string;
  string: string;
  /** Function and class names (GitHub's "entity"). */
  entity: string;
  /** Numbers, constants, attribute names. */
  constant: string;
  variable: string;
  tag: string;
  regexp: string;
  heading: string;
  link: string;
}

export interface Palette {
  /** Deepest surface (page inset, header in dark themes). */
  bgInset: string;
  /** Main canvas. */
  bg: string;
  /** Secondary surfaces: box headers, sidebars, code blocks. */
  bgMuted: string;
  border: string;
  /** Disabled text, placeholders, emphasized borders. */
  fgSubtle: string;
  fgMuted: string;
  fg: string;
  blue: string;
  cyan: string;
  green: string;
  yellow: string;
  orange: string;
  red: string;
  purple: string;
  pink: string;
}

export interface Theme {
  id: string;
  name: string;
  family: string;
  type: 'dark' | 'light';
  palette: Palette;
  syntax?: Partial<Syntax>;
}

export function syntaxFor(theme: Theme): Syntax {
  const p = theme.palette;
  return {
    comment: p.fgSubtle,
    keyword: p.purple,
    string: p.green,
    entity: p.blue,
    constant: p.orange,
    variable: p.yellow,
    tag: p.red,
    regexp: p.cyan,
    heading: p.blue,
    link: p.cyan,
    ...theme.syntax,
  };
}

